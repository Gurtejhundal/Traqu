const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createPrintHTML } = require('./print.mjs');

test('print output keeps Unicode, schedules, checked state, and source context', () => {
  const html = createPrintHTML({ name: 'A real plan', sections: [{ label: 'Delivery',
    schedule: '2026-11-12 to 2026-11-14', tasks: [{ title: 'Learn 中文 and ਪੰਜਾਬੀ 🚀', done: true, details: ['Note: Keep context'] }] }], source: ['Original guidance'] });
  for (const value of ['[x] Learn 中文 and ਪੰਜਾਬੀ 🚀', '2026-11-12 to 2026-11-14', 'Keep context', 'Original guidance', 'Generated by Traqu']) assert.ok(html.includes(value));
});

test('imported content cannot inject scripts, network assets, or active HTML into printing', () => {
  const html = createPrintHTML({ name: '<script>alert(1)</script>', sections: [{ label: '<iframe>', tasks: [
    { title: '<img src="https://evil.example" onerror="alert(1)">', details: ['</p><script>attack()</script>'] },
  ] }], source: ['<a href="javascript:attack()">link</a>'] });
  assert.ok(!html.includes('<script>'));
  assert.ok(!html.includes('<img'));
  assert.ok(!html.includes('<iframe>'));
  assert.ok(html.includes('&lt;img'));
  assert.ok(html.includes("default-src 'none'"));
});

test('print requests reject invalid structures and excessive task counts', () => {
  assert.throws(() => createPrintHTML({ name: 'Invalid' }));
  assert.throws(() => createPrintHTML({ name: 'Too big', source: [], sections: [{ label: 'One', tasks: Array.from({ length: 5001 }, () => ({ title: 'Task', details: [] })) }] }));
});
