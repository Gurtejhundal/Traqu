"""Recognize Traqu's own readable Word exports without tracking attribution."""
from io import BytesIO
import re
from docx import Document


def generated_document(content):
    document = Document(BytesIO(content))
    if not any(re.match(r'^Generated by Traqu\b', paragraph.text, re.I) for paragraph in document.paragraphs):
        return None
    tasks, outline = [], []
    label = 'General'
    dates = []
    in_source = False
    for paragraph in document.paragraphs:
        text = paragraph.text.strip()
        definition = paragraph.style
        properties = paragraph._p.pPr
        style_id = properties.pStyle.val if properties is not None and properties.pStyle is not None else ''
        style = definition.name if definition is not None else style_id
        if not text or style == 'Title' or re.match(r'^Generated by Traqu\b', text, re.I):
            continue
        if style.startswith('Heading'):
            in_source = in_source or text.lower() == 'preserved source'
            if not in_source:
                label = text
                dates = re.findall(r'\b\d{4}-\d{2}-\d{2}\b', text)
                continue
        if in_source:
            outline.append({'type': 'paragraph', 'text': text})
            continue
        action = re.match(r'^\[([ xX])\]\s+(.+)', text)
        if action:
            task = {'title': action[2], 'timeframe': label, 'is_done': action[1].lower() == 'x', 'blocks': []}
            if len(dates) == 2:
                task.update(start_date=dates[0], end_date=dates[1])
            elif len(dates) == 1:
                task.update(start_date=dates[0], end_date=dates[0])
            tasks.append(task)
        elif tasks:
            tasks[-1]['blocks'].append({'type': 'note', 'data': {'text': text}, 'position': len(tasks[-1]['blocks'])})
    return '\n'.join(paragraph.text for paragraph in document.paragraphs), tasks, outline
